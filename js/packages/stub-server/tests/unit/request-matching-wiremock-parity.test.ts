function verdict(
  mapping: Record<string, unknown>,
  method: string,
  url: string,
  headers: Headers,
  body: string,
): boolean {
  const contract = parseWireMockMapping(
    "mapping.json",
    JSON.stringify({ request: mapping, response: { status: 200 } }),
  );
  let parsed: unknown;
  try {
    parsed = JSON.parse(body);
  } catch {
    parsed = undefined;
  }
  return matchRequest(method, url, headers, parsed, [contract], body).matched;
}

describe("request matching parity with WireMock 3.13.2", () => {
  it.each(WIREMOCK_VERDICTS)("%j: %s", (mapping, _label, method, url, headers, body, matches) => {
    expect(verdict(mapping, method, url, headers, body)).toBe(matches);
  });

  it("should_accept_a_lower_case_method_unlike_wiremock", () => {
    // Deliberate difference: WireMock never matches "get"; stub-server has always upper-cased it.
    expect(verdict({ method: "get", urlPath: "/lower" }, "GET", "/lower", {}, "")).toBe(true);
  });

  it("should_never_match_xml_matchers_it_cannot_evaluate", () => {
    // WireMock evaluates XPath/XML; stub-server cannot, so the stub never matches (and reports
    // why) instead of matching every body as it used to.
    const mapping = {
      method: "POST",
      urlPath: "/x",
      bodyPatterns: [{ matchesXPath: { expression: "/root/name/text()", equalTo: "a" } }],
    };
    expect(verdict(mapping, "POST", "/x", {}, "<root><name>a</name></root>")).toBe(false);
    const contract = parseWireMockMapping(
      "x.json",
      JSON.stringify({ request: mapping, response: { status: 200 } }),
    );
    expect(contract.unsupportedMatchers).toEqual(["bodyPatterns[0].matchesXPath"]);
  });
});
