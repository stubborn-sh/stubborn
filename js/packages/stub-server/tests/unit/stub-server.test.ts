import { describe, it, expect, afterEach } from "vitest";
import { request as httpRequest } from "node:http";
import { StubServer } from "../../src/stub-server.js";
import { parseWireMockMapping } from "../../src/wiremock-parser.js";
import type { ParsedContract } from "../../src/contract-parser.js";

describe("StubServer", () => {
  let server: StubServer | null = null;

  afterEach(async () => {
    if (server !== null) {
      await server.stop();
      server = null;
    }
  });

  it("should_start_and_stop", async () => {
    server = new StubServer({ port: 0 });
    const port = await server.start();
    expect(port).toBeGreaterThan(0);
    expect(server.running).toBe(true);
    await server.stop();
    expect(server.running).toBe(false);
    server = null;
  });

  it("should_throw_when_starting_twice", async () => {
    server = new StubServer({ port: 0 });
    await server.start();
    await expect(server.start()).rejects.toThrow("already running");
  });

  it("should_serve_matching_contract", async () => {
    const contract: ParsedContract = {
      name: "test",
      request: { method: "GET", urlPath: "/api/hello" },
      response: {
        status: 200,
        headers: { "Content-Type": "application/json" },
        body: { message: "hello" },
      },
    };

    server = new StubServer({ port: 0 });
    server.setContracts([contract]);
    const port = await server.start();

    const response = await fetch(`http://127.0.0.1:${String(port)}/api/hello`);
    expect(response.status).toBe(200);
    const body = await response.json();
    expect(body).toEqual({ message: "hello" });
  });

  it("should_return_404_for_unmatched_request", async () => {
    server = new StubServer({ port: 0 });
    server.setContracts([]);
    const port = await server.start();

    const response = await fetch(`http://127.0.0.1:${String(port)}/api/nothing`);
    expect(response.status).toBe(404);
    const body = await response.json();
    expect(body.error).toBe("No matching contract found");
  });

  it("should_match_POST_with_body", async () => {
    const contract: ParsedContract = {
      name: "create",
      request: {
        method: "POST",
        urlPath: "/api/items",
        headers: { "Content-Type": "application/json" },
        body: { name: "widget" },
      },
      response: {
        status: 201,
        body: { id: "1", name: "widget" },
      },
    };

    server = new StubServer({ port: 0 });
    server.setContracts([contract]);
    const port = await server.start();

    const response = await fetch(`http://127.0.0.1:${String(port)}/api/items`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ name: "widget" }),
    });
    expect(response.status).toBe(201);
    const body = await response.json();
    expect(body).toEqual({ id: "1", name: "widget" });
  });

  it("should_handle_stop_when_not_running", async () => {
    server = new StubServer({ port: 0 });
    await server.stop(); // should not throw
    server = null;
  });
});

describe("StubServer with mappings generated by Stubborn Contract", () => {
  let server: StubServer | null = null;

  afterEach(async () => {
    if (server !== null) {
      await server.stop();
      server = null;
    }
  });

  async function serve(mapping: unknown): Promise<string> {
    server = new StubServer({ port: 0 });
    server.setContracts([parseWireMockMapping("mapping.json", JSON.stringify(mapping))]);
    const port = await server.start();
    return `http://127.0.0.1:${port}`;
  }

  // stubborn-sh/stubborn#165
  it("should_render_fromRequest_body_list_as_json", async () => {
    const base = await serve({
      request: { method: "POST", urlPath: "/orders" },
      response: {
        status: 200,
        body: '{"ids":{{{jsonPath request.body \'$.items[*].id\'}}} ,"url":"{{{request.url}}}"}',
        headers: { "Content-Type": "application/json", "X-Path": "{{{request.path}}}" },
        transformers: ["response-template", "stubborn-contract"],
      },
    });
    const post = (body: unknown): Promise<Response> =>
      fetch(`${base}/orders?x=1`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      });

    const two = await post({ items: [{ id: "1" }, { id: "2" }] });
    expect(two.status).toBe(200);
    expect(two.headers.get("x-path")).toBe("/orders");
    expect(await two.json()).toEqual({ ids: ["1", "2"], url: "/orders?x=1" });

    const one = await post({ items: [{ id: "1" }] });
    expect(await one.json()).toEqual({ ids: ["1"], url: "/orders?x=1" });
  });

  it("should_answer_500_for_an_unsupported_template_helper", async () => {
    const base = await serve({
      request: { method: "GET", urlPath: "/now" },
      response: { status: 200, body: "{{now}}", transformers: ["response-template"] },
    });
    const res = await fetch(`${base}/now`);
    expect(res.status).toBe(500);
    const error = (await res.json()) as { error: string; message: string };
    expect(error.error).toBe("Response template error");
    expect(error.message).toContain('unsupported helper or variable "now"');
  });

  it("should_serve_template_text_verbatim_without_the_response_template_transformer", async () => {
    const base = await serve({
      request: { method: "GET", urlPath: "/raw" },
      response: { status: 200, body: "{{{request.url}}}" },
    });
    expect(await (await fetch(`${base}/raw`)).text()).toBe("{{{request.url}}}");
  });

  // stubborn-sh/stubborn#166 — the client stub WireMockGroovyDslTests expects for a request
  // body holding an array of objects.
  it("should_match_nested_array_body_matchers_against_the_contract_request", async () => {
    const base = await serve({
      request: {
        urlPattern: "/[0-9]{2}",
        method: "GET",
        bodyPatterns: [
          { matchesJsonPath: "$.['errors'][*][?(@.['propertyName'] =~ /[0-9]{2}/)]" },
          { matchesJsonPath: "$.['errors'][*][?(@.['providerValue'] == 'Test')]" },
          { matchesJsonPath: "$[?(@.['lastName'] =~ /.*/)]" },
          { matchesJsonPath: "$[?(@.['firstName'] =~ /.*/)]" },
          { matchesJsonPath: "$[?(@.['birthDate'] =~ /[0-9]{4}-[0-9]{2}-[0-9]{2}/)]" },
          { matchesJsonPath: "$[?(@.['personalId'] =~ /[0-9]{11}/)]" },
        ],
      },
      response: {
        status: 200,
        body: '{"name":"Jan"}',
        headers: { "Content-Type": "application/json" },
        transformers: ["response-template", "foo-transformer"],
      },
    });
    const send = (errors: unknown): Promise<Response> =>
      getWithBody(`${base}/12`, { ...PERSON, errors });

    const matching = await send([
      { propertyName: "04", providerValue: "Test" },
      { propertyName: "08", providerValue: "Test" },
    ]);
    expect(matching.status).toBe(200);
    expect(await matching.json()).toEqual({ name: "Jan" });

    const wrongValue = await send([{ propertyName: "04", providerValue: "Other" }]);
    expect(wrongValue.status).toBe(404);

    const noArray = await send([]);
    expect(noArray.status).toBe(404);
  });

  // The client stub WireMockXmlStubStrategyTests expects for an XML contract with xPath body
  // matchers (byRegex, byEquality, byDate, byTimestamp, byTime, onlyAlphaUnicode).
  it("should_match_generated_xpath_body_matchers_against_the_contract_request", async () => {
    const base = await serve({
      request: {
        method: "GET",
        urlPath: "/get",
        headers: { "Content-Type": { matches: "application/xml.*" } },
        bodyPatterns: [
          { matchesXPath: { expression: "/test/duck/text()", matches: "[0-9]{3}" } },
          { matchesXPath: { expression: "/test/duck/text()", equalTo: "123" } },
          { matchesXPath: { expression: "/test/alpha/text()", matches: "[\\p{L}]*" } },
          { matchesXPath: { expression: "/test/alpha/text()", equalTo: "abc" } },
          { matchesXPath: { expression: "/test/number/text()", matches: "-?(\\d*\\.\\d+|\\d+)" } },
          { matchesXPath: { expression: "/test/aBoolean/text()", matches: "(true|false)" } },
          {
            matchesXPath: {
              expression: "/test/date/text()",
              matches: "(\\d\\d\\d\\d)-(0[1-9]|1[012])-(0[1-9]|[12][0-9]|3[01])",
            },
          },
          {
            matchesXPath: {
              expression: "/test/dateTime/text()",
              matches:
                "([0-9]{4})-(1[0-2]|0[1-9])-(3[01]|0[1-9]|[12][0-9])T(2[0-3]|[01][0-9]):([0-5][0-9]):([0-5][0-9])",
            },
          },
          {
            matchesXPath: {
              expression: "/test/time/text()",
              matches: "(2[0-3]|[01][0-9]):([0-5][0-9]):([0-5][0-9])",
            },
          },
          { matchesXPath: { expression: "/test/*/complex/text()", equalTo: "foo" } },
          { matchesXPath: { expression: "/test/duck/@type", equalTo: "xtype" } },
        ],
      },
      response: { status: 200, headers: { "Content-Type": "application/xml" } },
    });
    const contractBody =
      "\n<test>\n<duck type='xtype'>123</duck>\n<alpha>abc</alpha>\n<number>123</number>\n<aBoolean>true</aBoolean>\n<date>2017-01-01</date>\n<dateTime>2017-01-01T01:23:45</dateTime>\n<time>01:02:34</time>\n<valueWithoutAMatcher>foo</valueWithoutAMatcher>\n<valueWithTypeMatch>string</valueWithTypeMatch>\n<key><complex>foo</complex></key>\n</test>";
    const send = (body: string): Promise<Response> =>
      getWithBody(`${base}/get`, body, "application/xml");

    expect((await send(contractBody)).status).toBe(200);
    expect((await send(contractBody.replace(">abc<", ">abd<"))).status).toBe(404);
    expect((await send(contractBody.replace(">01:02:34<", ">25:02:34<"))).status).toBe(404);
    expect((await send("<test>not closed")).status).toBe(404);
  });
});

const PERSON = {
  personalId: "57593728525",
  firstName: "Bruce",
  lastName: "Lee",
  birthDate: "1985-12-12",
};

/** `fetch` cannot send a GET body; SCC contracts (and WireMock) can. */
function getWithBody(
  url: string,
  body: unknown,
  contentType = "application/json",
): Promise<Response> {
  return new Promise((resolve, reject) => {
    const data = typeof body === "string" ? body : JSON.stringify(body);
    const req = httpRequest(
      url,
      {
        method: "GET",
        headers: { "Content-Type": contentType, "Content-Length": Buffer.byteLength(data) },
      },
      (res) => {
        const chunks: Buffer[] = [];
        res.on("data", (chunk: Buffer) => chunks.push(chunk));
        res.on("end", () =>
          resolve(
            new Response(Buffer.concat(chunks).toString("utf-8"), { status: res.statusCode ?? 0 }),
          ),
        );
      },
    );
    req.on("error", reject);
    req.end(data);
  });
}
